// NeuralCheck V2 — SHA-256 (sub-phase 1c).
//
// Two entry points:
//   - sha256_compute(): hashes an arbitrary byte buffer with FIPS 180-4
//                       SHA-256. Used for self-verification (NIST "abc"
//                       test vector) and as the workload kernel.
//   - generate_sha_input(): fills a buffer with a deterministic
//                           per-byte LCG sequence, the verification
//                           workload's input. Per Q2.3 in
//                           IMPLEMENTATION_NOTES_V2.md.
//
// Sub-phase 1c ships only the scalar implementation. ARMv8 SHA-2 crypto
// extensions (HWCAP_SHA2 + vsha256hq_u32 family) produce the same hash
// bit-for-bit but ~3-5× faster; they're deferred until 1c-prime when
// the production stress path needs the throughput. Verification logic
// is identical regardless of implementation, since the output is bit-
// exact across all correct SHA-256 impls.

#pragma once

#include <cstddef>
#include <cstdint>

namespace neuralcheck::stress {

// SHA-256 produces a 256-bit (32-byte) digest.
constexpr size_t kSha256DigestBytes = 32;

// Computes SHA-256 of [input, input + len) and writes the digest into
// out (must point to at least kSha256DigestBytes of writable memory).
// Bit-exact with FIPS 180-4 — no platform dependency.
void sha256_compute(const uint8_t* input, size_t len, uint8_t out[kSha256DigestBytes]) noexcept;

// Fills buf with len bytes generated by a 32-bit LCG seeded with the
// canonical NeuralCheck stress seed (0x12345678). Each byte is the
// XOR of the high byte of the LCG state with 0xA5 — pattern-free but
// 100% deterministic. Output is identical on every device, every run.
void generate_sha_input(uint8_t* buf, size_t len) noexcept;

// Self-test: hashes the FIPS 180-4 "abc" test vector and returns true
// iff the digest matches the canonical expected value. Detects a broken
// SHA implementation before it's trusted to produce reference values
// for stress workloads. Cheap (~100 µs) — call before runSha256Test().
bool sha256_self_test() noexcept;

}  // namespace neuralcheck::stress
