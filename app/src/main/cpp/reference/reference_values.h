// =====================================================================
// NeuralCheck V2 — verification reference values.
// =====================================================================
//
// Each constant below is the precomputed expected output of a stress
// kernel under a fixed deterministic input. A device that produces a
// different value under the same input has a CPU/memory/silicon defect
// (silent data corruption, bad cache line, marginal transistor, dying
// memory cell) — that is the entire point of the verification step.
//
// Source-of-truth policy:
//   - For values that are well-known mathematical constants (e.g. π(N))
//     the reference is taken from the published constant. No platform
//     dependency.
//   - For values computed from a kernel + fixed seed (NEON FMA trace,
//     SHA-256 of a generated 1 MB buffer) the reference is computed
//     once on a known-good reference device with the same source and
//     compile flags as production: -O3, -ffp-contract=off, no
//     -ffast-math (see CMakeLists.txt + IMPLEMENTATION_NOTES_V2.md
//     Q2.5). The reference device, NDK version, and date are recorded
//     in a comment alongside each value.
//
// Sub-phases land their references progressively:
//   1b — PRIME_SIEVE_10M_*       (this file, current)
//   1c — SHA256_REF_HASH         (1 MB buffer hash)
//   1d — NEON_FMA_TRACE_*        (matrix trace + tolerance + row CRCs)
//   1e — MEMORY_*_REFERENCE      (March / Walking / Random+SHA refs)
//
// Each addition bumps VERIFICATION_REF_VERSION below.

#pragma once

#include <cstdint>

// Bumped whenever ANY reference value or kernel input is changed. The
// running scan writes this number into the time-series footer so a
// future analyst can tell which reference set produced a given report
// and reject mixed comparisons.
#define VERIFICATION_REF_VERSION 1

// =====================================================================
// PRIME_SIEVE  (sub-phase 1b)
// =====================================================================
//
// π(10,000,000) — the count of primes p such that 2 ≤ p ≤ 10⁷.
//
// This is a published mathematical constant. Cross-checked against:
//   - OEIS A006880 (prime counting function values at 10ⁿ)
//   - https://primes.utm.edu/howmany.html
//   - "Handbook of Mathematical Functions" (Abramowitz & Stegun)
//
// No platform dependency — every correct implementation of Eratosthenes
// MUST return exactly this number. Any deviation indicates a CPU defect:
//   - Bit flip in the sieve buffer (memory cell or cache line bad)
//   - Off-by-one in a counter register
//   - Branch predictor mis-issued a "skip" on a prime
// All three are silent failures invisible to throughput-only metrics —
// hence this verification is mandatory in V2 (master plan §1, principle 2).

#define PRIME_SIEVE_10M_LIMIT     10000000u
#define PRIME_SIEVE_10M_REFERENCE 664579

// ---------------------------------------------------------------------
// PRIME_SIEVE_1M — the limit of the CPU known-answer check D ONLY
// (fieldsVersion 70, contract docs/FV68_CONTRACT.md section 7-t).
// ---------------------------------------------------------------------
//
// π(1,000,000) = 78,498 — the same published constant family as above
// (OEIS A006880, 10ⁿ values: π(10⁶) = 78498). D's sieve array is
// 1,000,001 bytes (0.95 MiB) instead of 10,000,001 (9.54 MiB); the device
// check measured the 10⁷ sieve as 88–94 % of D's time, which broke the
// "D <= 1 % of the phase" acceptance on slower devices.
//
// ONLY known_answer.cpp (sieve_known_answer) reads these two. The 10M pair
// above stays for runPrimeSieveTest and the legacy production CPU stress,
// which are not D. The limit goes to the app through the JNI result array
// (the sieve layout v2, slot 5): Kotlin keeps no copy of it (rule 24).
// A guard test (KnownAnswerReferenceTest) sieves to this limit on the JVM
// and compares with this reference, so the two numbers cannot drift apart.

#define PRIME_SIEVE_1M_LIMIT     1000000u
#define PRIME_SIEVE_1M_REFERENCE 78498

// =====================================================================
// SHA-256  (sub-phase 1c)
// =====================================================================
//
// SHA-256 of a 1 MB buffer generated by the canonical NeuralCheck LCG
// (seed = 0x12345678; see generate_sha_input() in stress/sha256.cpp).
//
// Reference computed off-device via Python's hashlib.sha256, which is a
// well-audited reference implementation of FIPS 180-4. Cross-verified by:
//   - The C++ scalar implementation in stress/sha256.cpp (same input →
//     same output by construction; SHA-256 is bit-exact across every
//     correct implementation).
//   - The FIPS 180-4 §A.1 "abc" test vector handled by sha256_self_test()
//     before this reference is trusted.
//
// SHA-256 is bit-exact, so unlike the FP32 NEON FMA reference there is
// NO tolerance and NO platform variance. A device that produces a
// different hash has either:
//   - A bit flip in the input buffer (bad RAM cell)
//   - A computation error in the SHA round function (CPU defect)
//   - Memory corruption between buffer write and SHA read
// All three are silent failures invisible to throughput metrics.

#define SHA256_TEST_INPUT_SIZE  (1u << 20)  // 1 MiB

// Hash of generate_sha_input(buf, 1 MiB) with seed 0x12345678.
// Computed via Python:
//   state = 0x12345678
//   for i in range(1<<20):
//       state = (state * 0x9E3779B1 + 0xDEADBEEF) & 0xFFFFFFFF
//       buf[i] = ((state >> 24) ^ 0xA5) & 0xFF
//   hashlib.sha256(buf).hexdigest()
// → 83df70dc1d2813a9d25968780d3e9606583f0e1a83a4a5c5ab579bafb9f943a5
static constexpr uint8_t SHA256_REF_HASH[32] = {
    0x83, 0xDF, 0x70, 0xDC, 0x1D, 0x28, 0x13, 0xA9,
    0xD2, 0x59, 0x68, 0x78, 0x0D, 0x3E, 0x96, 0x06,
    0x58, 0x3F, 0x0E, 0x1A, 0x83, 0xA4, 0xA5, 0xC5,
    0xAB, 0x57, 0x9B, 0xAF, 0xB9, 0xF9, 0x43, 0xA5,
};

