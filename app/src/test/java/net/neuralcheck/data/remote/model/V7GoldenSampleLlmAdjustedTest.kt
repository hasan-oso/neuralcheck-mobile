class V7GoldenSampleLlmAdjustedTest {

    private val gson = Gson()

    private fun loadSample(): AiAnalysisResponse {
        val stream = javaClass.classLoader!!.getResourceAsStream(
            "contract/v7-client-payload-sample-llm-adjusted.json"
        ) ?: error(
            "contract/v7-client-payload-sample-llm-adjusted.json not found on the " +
                "test classpath — expected at app/src/test/resources/contract/"
        )
        return InputStreamReader(stream, Charsets.UTF_8).use { reader ->
            gson.fromJson(reader, AiAnalysisResponse::class.java)
        }
    }

    @Test
    fun `the LLM_ADJUSTED golden sample parses at all, through the real production deserializer`() {
        // The core regression this whole fix targets: before
        // LenientStringListAdapter + the list-of-strings retype, an
        // LLM_ADJUSTED category's array-shaped adjustmentEvidence hit a
        // plain String field and threw JsonSyntaxException out of
        // gson.fromJson with no local catch — AiScoringEngine's
        // catch(Throwable) then discarded the ENTIRE response, not just
        // this field. This test would have failed with that exception
        // before the fix; it must merely not throw now.
        val r = loadSample()
        assertNotNull(r)
        assertEquals(AiPipeline.V7_FINDINGS_BASED, r.pipeline)
    }

    @Test
    fun `root fields and all 15 categories still arrive, none silently dropped by the LLM_ADJUSTED category`() {
        val r = loadSample()
        assertEquals("ar", r.language)
        // Rule 23 — resynced 2026-10-07 from neuralcheck-backend@d5b6c29
        // (was NC-6LS4A7 under the c7446a4 sample, NC-XDFWAK before that) —
        // shortId is randomly regenerated per run, no significance beyond
        // "the fixture parses".
        assertEquals("NC-ZR3QHZ", r.shortId)
        assertEquals(false, r.isFreeTrial)
        assertEquals("deepseek-flash", r.aiModel)
        assertEquals("C", r.overall?.letter)
        val categories = r.categories!!
        assertEquals(15, categories.size)
        assertEquals(
            setOf(
                "battery", "thermal", "cpu", "gpu", "display", "memory", "storage",
                "camera", "gps", "security", "sensors", "cellular", "wireless",
                "audio", "input"
            ),
            categories.keys
        )
        // Rule 23 — resynced 2026-09-30 from neuralcheck-backend@c7446a4:
        // was 31; six issues (ISS-SEC-05, ISS-SEC-06, DISC-SEC-07,
        // DISC-CM-08, DISC-T-01, DISC-T-02) removed from this sample.
        assertEquals(25, r.issues?.size)
        assertTrue("a report with overall.letter present must read complete", r.isComplete())
    }

    @Test
    fun `resync 2026-10-07 (backend@d5b6c29) — storage is DETERMINISTIC B under a real LOW_CATEGORY_COVERAGE ceiling, no adjustment fields`() {
        // Rule 23 — REPLACES the test of the same slot (resynced
        // 2026-09-25, القرار ٩٥ البند ٣, backend@90fb816), which asserted
        // storage `letter == "C"` with `letterCeilingReason` declared null
        // ("storage's self-referencing adjustment is now REJECTED").
        // That letter and that null were the c7446a4-era content; the
        // d5b6c29 sample's storage is B under a LOW_CATEGORY_COVERAGE
        // ceiling (asserted in the ceiling test below). What this test
        // still proves is unchanged and still real: storage arrives
        // DETERMINISTIC, with BOTH adjustment fields null — the real "no
        // adjustment happened" shape, not a parse failure — and the old
        // self-referencing LLM_ADJUSTED shape stays rejected (rule 33).
        val storage = loadSample().categories!!.getValue("storage")

        assertEquals("MEASURED", storage.state)
        assertEquals("B", storage.letter)
        assertEquals("DETERMINISTIC", storage.letterSource)
        assertNull("no adjustment was accepted, so no reason to report", storage.adjustmentReason)
        assertNull("no adjustment was accepted, so no evidence to report", storage.adjustmentEvidence)

        assertEquals(1.0, storage.coverage!!, 0.00000001)
        assertNull(storage.reason)
        assertEquals(listOf("S-01", "S-02", "S-03", "S-04", "S-05", "S-06"), storage.testIds)
    }

    @Test
    fun `non-LLM_ADJUSTED categories still carry null adjustmentEvidence, unaffected by storage's array`() {
        // Guards against the array-vs-null branch of LenientStringListAdapter
        // leaking state across category entries in the same map.
        val categories = loadSample().categories!!
        for (key in listOf("battery", "thermal", "cpu", "gpu", "display", "memory")) {
            val cat = categories.getValue(key)
            if (cat.letterSource != "LLM_ADJUSTED") {
                assertNull("$key.adjustmentEvidence must stay null (not LLM_ADJUSTED)", cat.adjustmentEvidence)
            }
        }
    }

    @Test
    fun `resync 2026-09-25 (القرار ٩٢ البند ١، backend@4d6c488) — this sample NOW declares letterCeilingReason on every category, none missing`() {
        // Rule 23 — REPLACES the old test of the same slot, which proved
        // the OPPOSITE: before this resync, this fixture predated the
        // 154f3f2 letterCeilingReason update entirely (every category's
        // raw JSON lacked the key). The backend regenerated this sample
        // 2026-09-25 — it is no longer real material for the "genuinely
        // absent key" (NOT_DECLARED) case; that classifier branch keeps
        // its OTHER, hand-built coverage elsewhere in this suite
        // (AiV7PresentationTest's `classifyLetterCeilingReason` tests,
        // independent of this fixture).
        val categories = loadSample().categories!!

        val stream = javaClass.classLoader!!.getResourceAsStream(
            "contract/v7-client-payload-sample-llm-adjusted.json"
        )!!
        val rawJson = InputStreamReader(stream, Charsets.UTF_8).readText()
        assertEquals(
            "every one of the 15 categories now declares the key (present, whether null or an " +
                "object) — none reported missing any more",
            emptySet<String>(),
            categoriesMissingLetterCeilingReason(rawJson)
        )

        // Seven categories carry a real LOW_CATEGORY_COVERAGE ceiling
        // object (their letter is B, asserted in the next test) — the
        // other eight declare the key as an explicit JSON null (a real "no gate ceilinged this category" answer, parsing
        // to Kotlin `null` exactly like the object case's absence would —
        // that ambiguity is why `categoriesMissingLetterCeilingReason`
        // exists as a separate, independently-computed signal).
        // Rule 23 — resynced 2026-09-30 from neuralcheck-backend@c7446a4:
        // gps moved OUT of this set (was one of seven). It is now
        // UNMEASURED/DECLARED_BUT_NONE_EXECUTED with letterCeilingReason
        // null, not a real LOW_CATEGORY_COVERAGE object — so it now falls
        // into the else branch below, asserted null like the others.
        // Rule 23 — resynced 2026-10-07 from neuralcheck-backend@d5b6c29:
        // storage moved INTO this set (was declared null, letter C) —
        // it now carries a real LOW_CATEGORY_COVERAGE object, letter B.
        // So the set is seven again; it is a DIFFERENT seven than the
        // pre-c7446a4 one (storage in, gps out).
        val withCeilingText = setOf(
            "cellular", "display", "gpu", "memory", "sensors", "storage", "wireless"
        )
        for ((key, cat) in categories) {
            if (key in withCeilingText) {
                assertNotNull("$key must now carry a real letterCeilingReason object", cat.letterCeilingReason)
                assertEquals("LOW_CATEGORY_COVERAGE", cat.letterCeilingReason?.name)
                assertEquals("B", cat.letterCeilingReason?.ceilingLetter)
                assertTrue(
                    "$key.letterCeilingReason.text must be real, non-blank text",
                    cat.letterCeilingReason?.text?.isNotBlank() == true
                )
                // Rule 23 — resynced 2026-10-07 from neuralcheck-backend@d5b6c29:
                // the sentence's second half CHANGED. Before: "... — حرف
                // مسقوف: لم يُقَس في هذه الفئة أيّ اختبار معتمد قياساً
                // للحالة." After: "... — أعلى حرف لهذه الفئة B في هذا
                // الإصدار: اختباراتها تتأكّد من وجود المكوّنات وعملها،
                // ولا تقيس أداءها بعد." The old wording is gone from the
                // sample (it said "nothing measured", false for a
                // MEASURED category); asserting the new tail here means a
                // reversion of the backend wording fails THIS test.
                assertTrue(
                    "$key.letterCeilingReason.text must carry the d5b6c29 wording",
                    cat.letterCeilingReason!!.text!!.endsWith(
                        "أعلى حرف لهذه الفئة B في هذا الإصدار: اختباراتها تتأكّد من وجود المكوّنات وعملها، ولا تقيس أداءها بعد."
                    )
                )
            } else {
                assertNull(
                    "$key.letterCeilingReason must parse null — declared key, real \"no ceiling\" answer, " +
                        "not the old \"key absent\" shape",
                    cat.letterCeilingReason
                )
            }
        }
    }

    @Test
    fun `resync 2026-10-07 — the seven ceilinged categories letter is B under LOW_CATEGORY_COVERAGE`() {
        // Rule 23 — this specific regression (A->B on these keys)
        // was not asserted by name before the resync (the old test only
        // checked categories.keys/size, not individual non-storage
        // letters), so this is new coverage, not a replacement of a wrong
        // assertion — recorded here so a future resync's diff has
        // something concrete to compare against.
        // Rule 23 — resynced 2026-09-30 from neuralcheck-backend@c7446a4:
        // gps removed from this list (was seven keys). gps.letter is now
        // null (UNMEASURED), not "B" — asserted separately below.
        val categories = loadSample().categories!!
        // Rule 23 — resynced 2026-10-07 from neuralcheck-backend@d5b6c29:
        // storage added to this list (was "C" under c7446a4, declared
        // null ceiling) — it is B now, like the other six.
        for (key in listOf("cellular", "display", "gpu", "memory", "sensors", "storage", "wireless")) {
            assertEquals("$key must be B (ceilinged by LOW_CATEGORY_COVERAGE)", "B", categories.getValue(key).letter)
        }
        assertNull(
            "gps must now be null (UNMEASURED, DECLARED_BUT_NONE_EXECUTED) — no longer B",
            categories.getValue("gps").letter
        )
        // storage's letter history (kept for the next resync's diff):
        // "D" (LLM_ADJUSTED, self-referencing evidence) -> "C" (90fb816,
        // القرار ٩٥ البند ٣, evidence rejected) -> "B" (d5b6c29, ceilinged
        // by LOW_CATEGORY_COVERAGE). Asserted with the other six above;
        // see the storage-specific test for its adjustment fields.
        assertEquals("B", categories.getValue("storage").letter)
    }
}
