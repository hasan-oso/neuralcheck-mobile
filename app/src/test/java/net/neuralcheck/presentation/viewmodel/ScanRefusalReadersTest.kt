/**
 * The app's REAL readers over the server's refusal bodies - A-SUB wave 1, the reader tests of the order (rule 41: a reader is tested with a sample made by the real producer, and rule 30: what the
 * reader PRODUCES from the value, not only that the value arrived).
 *
 * Samples, each named (none invented):
 *  - the five analysis bodies: **from probe-wire, not from production** ([ScanRefusalWire.ANALYZE_BODIES]; backend report `backend-engineer-asub-server-questions-3b7fbd2-2026-10-17.md` lines 113-117, the
 *    server's own `probe-wire.js` at neuralcheck-backend `3b7fbd2`);
 *  - the join's new refusal and `createScanSession`'s two new refusals: **built from the text of the order, not from probe-wire and not from production** ([ScanRefusalWire]);
 *  - the ordinary success body of an analysis: `app/src/test/resources/contract/v7-client-payload-sample.json`, copied from neuralcheck-backend's golden sample generated by the real chain with no model call
 *    (its README), standing for the stored reply the server now serves a completed session's lost-reply retry (order of 2026-10-17: «جسم ردّ عادي»). Whether the SERVER serves it is the server's; this
 *    only shows what the app does with such a reply.
 * Each body goes through the SDK's own parser ([SessionWireFixtures.exceptionFromWire]); the readers are the app's real ones: [ReasonCodeRead], `failureSaysNoConnection`, [LeaveFailureRead],
 * `sessionErrorMessage` for every call, the real engine. Arabic and Turkish run the same tests.
 */
abstract class ScanRefusalReadersBase {

    internal abstract fun approved(text: ApprovedSessionTexts.Text): String

    private val context: Context get() = ApplicationProvider.getApplicationContext()

    private fun existing(id: Int) = context.getString(id)

    private val fiveCodes = listOf("NO_CREDIT", "SUBSCRIPTION_EXPIRED", "FREE_DEVICE_USED", "SHOP_NO_CREDIT", "SHOP_SUBSCRIPTION_EXPIRED")

    // ---- what the SDK makes of the bodies ----

    @Test
    fun `the SDK reads each probe-wire body as PERMISSION_DENIED with details holding the reasonCode and nothing else`() {
        for (code in fiveCodes) {
            val e = ScanRefusalWire.analyzeException(code)
            assertEquals(code, FirebaseFunctionsException.Code.PERMISSION_DENIED, e.code)
            val details = e.details as Map<*, *>
            assertEquals("$code: details holds reasonCode alone (the report's detailsKeys)", setOf("reasonCode"), details.keys)
            assertEquals(code, details["reasonCode"])
        }
    }

    /**
     * Rule 41, the second half: every synthetic sample in the tests matches what the real producer makes. The builder the other tests use ([SessionWireFixtures.wireBody]) writes, for the same
     * status, message and code, the very bytes probe-wire printed - so the bodies the tests BUILD (the join's and the create's, from the order's text) have the producer's shape.
     */
    @Test
    fun `the test builder writes the bytes the server's own probe printed`() {
        val messages = mapOf(
            "NO_CREDIT" to ScanRefusalWire.NO_CREDIT_MESSAGE, "SUBSCRIPTION_EXPIRED" to ScanRefusalWire.EXPIRED_MESSAGE, "FREE_DEVICE_USED" to ScanRefusalWire.FREE_DEVICE_MESSAGE,
            "SHOP_NO_CREDIT" to ScanRefusalWire.NO_CREDIT_MESSAGE, "SHOP_SUBSCRIPTION_EXPIRED" to ScanRefusalWire.EXPIRED_MESSAGE
        )
        for (code in fiveCodes) {
            assertEquals(code, ScanRefusalWire.ANALYZE_BODIES.getValue(code), SessionWireFixtures.wireBody("PERMISSION_DENIED", messages.getValue(code), code))
        }
    }

    // ---- what the app's readers produce ----

    /** Order of 2026-10-20: the two newer codes join the five (rule 23: this REPLACES the title and the list of `names each of the five`). */
    @Test
    fun `the reasonCode reader names each of the five and the two of 2026-10-20 - Known, never Unrecognized, never Absent - and no reader mistakes one for a lost connection`() {
        val all = fiveCodes.map { it to ScanRefusalWire.analyzeException(it) } +
            ScanRefusalWire.CREATE_BODIES.map { it.reasonCode!! to it.exception() } +
            (ScanRefusalWire.JOIN_SHOP_SUBSCRIPTION_EXPIRED.reasonCode!! to ScanRefusalWire.JOIN_SHOP_SUBSCRIPTION_EXPIRED.exception()) +
            (ScanRefusalWire.STORED_REPORT_REFUSAL.reasonCode!! to ScanRefusalWire.STORED_REPORT_REFUSAL.exception())
        assertTrue("both codes of 2026-10-20 are in the list", setOf("SCAN_REPORT_NOT_AVAILABLE", "SHOP_PLAN_REQUIRED").all { c -> all.any { it.first == c } })
        for ((code, e) in all) {
            val read = ReasonCodeRead.of(e)
            assertTrue("$code is a code the app knows: $read", read is ReasonCodeRead.Known)
            assertEquals(code, SessionErrorCode.values().single { it.wire == code }, (read as ReasonCodeRead.Known).code)
            assertTrue("$code: the server answered, so it is no connection failure", !failureSaysNoConnection(e))
            assertEquals("$code: a leave that got such a refusal is a refused leave, not an expiry, not a stranger, not offline", LeaveFailureRead.Refused, LeaveFailureRead.of(e))
        }
    }

    /** What every call shows for each of the five, written out here (not read from the code under test): the key of the text and the text itself. */
    private fun expected(call: SessionCall, code: String): Pair<String, String> = when (call) {
        SessionCall.JOIN_TYPED ->
            if (code == "SHOP_SUBSCRIPTION_EXPIRED") "shop_subscription_expired" to approved(ApprovedSessionTexts.SHOP_SUBSCRIPTION_EXPIRED)
            else "error_generic" to existing(R.string.error_generic)
        SessionCall.JOIN_QR ->
            if (code == "SHOP_SUBSCRIPTION_EXPIRED") "shop_subscription_expired" to approved(ApprovedSessionTexts.SHOP_SUBSCRIPTION_EXPIRED)
            else "qr_join_failed" to existing(R.string.qr_join_failed)
        SessionCall.CANCEL_OWNER, SessionCall.CANCEL_CUSTOMER -> "error_generic" to existing(R.string.error_generic)
        SessionCall.CREATE ->
            when (code) {
                "SHOP_SUBSCRIPTION_EXPIRED" -> "subscription_expired" to approved(ApprovedSessionTexts.SUBSCRIPTION_EXPIRED)
                "SHOP_NO_CREDIT" -> "subscription_no_scans" to approved(ApprovedSessionTexts.NO_CREDIT_EXISTING)
                "SHOP_PLAN_REQUIRED" -> "shop_plan_required" to approved(ApprovedSessionTexts.SHOP_PLAN_REQUIRED)
                else -> "session_error_generic" to existing(R.string.session_error_generic)
            }
    }

    /**
     * Order of 2026-10-20 (rule 30: every enumerated value of the new codes, on every call, each in both languages): `SHOP_PLAN_REQUIRED` has a text on the create alone; `SCAN_REPORT_NOT_AVAILABLE` has none on any
     * session call (it is the analysis' code - the engine path test shows its text) - there each call shows what it showed for a code with no text, and prints it.
     */
    @Test
    fun `every call shows, for each of the two codes of 2026-10-20, the text its table gives - the plan text on the create alone, and every call is covered`() {
        assertEquals("a new call needs its row in this test", 5, SessionCall.values().size)
        for (call in SessionCall.values()) {
            for (code in listOf("SHOP_PLAN_REQUIRED", "SCAN_REPORT_NOT_AVAILABLE")) {
                val (key, text) = expected(call, code)
                val lines = mutableListOf<String>()
                val before = net.neuralcheck.util.EvalCardLog.sink
                net.neuralcheck.util.EvalCardLog.sink = { lines.add(it) }
                val shown = try {
                    sessionErrorMessage(context, call, SessionWireFixtures.Refusal("x", "PERMISSION_DENIED", "a message the app never reads", code).exception())
                } finally {
                    net.neuralcheck.util.EvalCardLog.sink = before
                }
                assertEquals("${call.wire} x $code", text, shown)
                val line = lines.single { it.startsWith("session-refused call=${call.wire} ") }
                assertTrue("${call.wire} x $code: $line", line.contains(" reasonCode=$code ") && line.endsWith(" shown=$key"))
            }
        }
    }

    @Test
    fun `every call shows, for each of the five codes, the text its table gives - and every call is covered`() {
        assertEquals("a new call needs its row in this test", 5, SessionCall.values().size)
        for (call in SessionCall.values()) {
            for (code in fiveCodes) {
                val (key, text) = expected(call, code)
                val lines = mutableListOf<String>()
                val before = net.neuralcheck.util.EvalCardLog.sink
                net.neuralcheck.util.EvalCardLog.sink = { lines.add(it) }
                val shown = try {
                    sessionErrorMessage(context, call, ScanRefusalWire.analyzeException(code))
                } finally {
                    net.neuralcheck.util.EvalCardLog.sink = before
                }
                assertEquals("${call.wire} x $code", text, shown)
                val line = lines.single { it.startsWith("session-refused call=${call.wire} ") }
                assertTrue("${call.wire} x $code: $line", line.contains(" reasonCode=$code ") && line.endsWith(" shown=$key"))
            }
        }
    }

    // ---- the engine: the codes the analysis now carries on a session, and the served reply ----

    private fun report(scanId: String) = ScanReport(
        scanId = scanId, scanType = ScanType.GENERAL, linkedScanId = null, deviceInfo = mock<DeviceInfo>(),
        scanMetadata = ScanMetadata(0L, 1L, 90, 80, 30f, 1L, true, null, "test"),
        functionalResults = emptyList(), timeSeriesSummary = null, antiTamperFlags = emptyList(), technicianInput = null, peerInput = null
    )

    private fun engineOver(h: RealJoinPathHarness): AiScoringEngine {
        val texts = context
        val engineContext = mock<Context> { on { getString(any<Int>()) }.thenAnswer { inv -> texts.getString(inv.getArgument<Int>(0)) } }
        val fingerprint = mock<BehaviorFingerprint>(defaultAnswer = Mockito.RETURNS_DEEP_STUBS)
        val builder = mock<BehaviorFingerprintBuilder> { on { build(any(), anyOrNull(), anyOrNull(), anyOrNull(), anyOrNull()) } doReturn fingerprint }
        val timeSeries = mock<TimeSeriesRepository> { on { getReader() } doReturn mock<TimeSeriesFileReader>() }
        return AiScoringEngine(
            context = engineContext, fingerprintBuilder = builder, firebaseService = h.service, timeSeriesRepository = timeSeries,
            scanSessionHolder = h.holder, scanSessionRecords = h.records, authManager = h.authManager,
            evaluationSubmitter = mock<EvaluationSubmitter>(), analysisProgress = AnalysisProgress()
        )
    }

    private fun joinSession(h: RealJoinPathHarness, id: String) =
        h.holder.setFromJoin(JoinSessionResult(sessionId = id, ownerId = "owner-1", status = "scanning", evaluationEnabled = true))

    private val servedReply: Any? by lazy {
        val dir = listOf("src/test/resources/contract", "app/src/test/resources/contract").map(::File).first { it.isDirectory }
        Gson().fromJson(File(dir, "v7-client-payload-sample.json").readText(), Map::class.java)
    }

    @Test
    fun `the session-state codes the analysis now carries break nothing - the text of before, the record kept for the retry, the scan left as a failure (every code)`() {
        for (code in listOf("SESSION_NOT_PARTICIPANT", "SESSION_NOT_STARTED", "SESSION_COMPLETED", "SESSION_CANCELLED", "SESSION_EXPIRED", "SESSION_EXPIRES_AT_INVALID", "SESSION_STATUS_UNKNOWN")) {
            RealJoinPathHarness(signedInAtStart = false).use { h ->
                val engine = engineOver(h)
                joinSession(h, "sess-1")
                h.startScan("scan-0001")
                h.analyzeFailure = SessionWireFixtures.Refusal("x", "PERMISSION_DENIED", "جلسة الفحص غير صالحة", code).exception()
                val result = runBlocking { engine.calculateScore(report("scan-0001")) }
                assertNull("$code: no analysis", result.aiAnalysis)
                assertEquals("$code: the server's own text, as before", "جلسة الفحص غير صالحة", result.error)
                assertTrue("$code: not 'still processing'", !result.analysisInProgress)
                assertNotNull("$code: the scan's record is kept - a retry sends the same session", h.records.sessionFor("scan-0001", ScanSessionRecords.Use.ANALYSIS))
                assertTrue("$code: the line says there is no approved text", h.logLines.any { it.contains(" reasonCode=$code raw=- combination=no-approved-text ") })
            }
        }
    }

    @Test
    fun `a completed session's retry that the server now answers with the stored reply is an ordinary success - the record is spent, the holder emptied, no error`() {
        RealJoinPathHarness(signedInAtStart = false).use { h ->
            val engine = engineOver(h)
            joinSession(h, "sess-1")
            h.startScan("scan-0001")
            // the first attempt: the reply was lost on the way (a timeout) - the failure keeps the record
            h.analyzeFailure = java.io.IOException("Callable 'analyzeDevice' timed out after 300000ms")
            val first = runBlocking { engine.calculateScore(report("scan-0001")) }
            assertNull(first.aiAnalysis)
            assertNotNull("the record survived the lost reply", h.records.sessionFor("scan-0001", ScanSessionRecords.Use.ANALYSIS))

            // the retry: the session is `completed`; before this wave the server refused it, now it serves the stored reply (an ordinary body)
            h.analyzeFailure = null
            h.analyzeResponse = servedReply
            val retry = runBlocking { engine.calculateScore(report("scan-0001")) }

            assertNotNull("the served reply reads as an analysis", retry.aiAnalysis)
            assertNull("and shows no error", retry.error)
            assertTrue(!retry.analysisInProgress)
            assertNull("the success spends the scan's record", h.records.sessionFor("scan-0001", ScanSessionRecords.Use.ANALYSIS))
            assertNull("and empties the holder", h.holder.getInfo())
            assertEquals(2, h.analyzeRequests.size)
            for ((i, request) in h.analyzeRequests.withIndex()) {
                assertEquals("call ${i + 1} carried the session the scan started in", "sess-1", (request as Map<*, *>)["sessionId"])
            }
            assertTrue("no refusal line was printed for the served reply", h.logLines.none { it.startsWith("scan-refused ") })
        }
    }
}

